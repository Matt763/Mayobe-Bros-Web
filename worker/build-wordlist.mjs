// Builds worker/src/wordlist.js from the editable lists in worker/wordlists/*.json.
//
//   node worker/build-wordlist.mjs          write worker/src/wordlist.js
//   node worker/build-wordlist.mjs --check  fail if worker/src/wordlist.js is out of date (used by the tests)
//
// Each list file has the shape { words: [], stems: [], phrases: [], scam: [] } (extra keys such as "sources" and "notes" are
// ignored). exclude.json ({ "drop": [...] }) lists entries to remove from every list after a false alarm. Everything is lowercased and reduced to a-z and single spaces, then merged and sorted. The module in
// worker/src/moderation.js explains how each array is used.

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, 'wordlists');
const out = join(here, 'src', 'wordlist.js');

const norm = (s) => String(s).normalize('NFKD').replace(/\p{M}+/gu, '').toLowerCase().replace(/['’`´]/g, '').replace(/[^a-z ]+/g, ' ').replace(/\s+/g, ' ').trim();

export function buildWordlist() {
  const sets = { words: new Set(), stems: new Set(), phrases: new Set(), scam: new Set() };
  const dropped = [];
  const exclude = new Set(JSON.parse(readFileSync(join(dir, 'exclude.json'), 'utf8')).drop.map(norm)); // entries removed from every list (false alarms)
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.json') && f !== 'exclude.json').sort()) {
    const data = JSON.parse(readFileSync(join(dir, file), 'utf8'));
    for (const key of Object.keys(sets)) {
      for (const item of data[key] || []) {
        const n = norm(item);
        if (!n || exclude.has(n)) continue;
        const multi = n.includes(' ');
        if (key === 'words' && multi) { sets.phrases.add(n); continue; } // a phrase filed under words
        if (key === 'words' && n.length < 2) { dropped.push(`${file}: word too short: ${item}`); continue; }
        if (key === 'stems' && (multi || n.length < 6)) { dropped.push(`${file}: stem must be one word of 6+ letters: ${item}`); continue; }
        if ((key === 'phrases' || key === 'scam') && !multi) {
          if (key === 'phrases') sets.words.add(n); else if (n.length >= 5) sets.scam.add(n); // single-word scam hints are too loose
          continue;
        }
        sets[key].add(n);
      }
    }
  }
  // a stem that is already a whole word adds nothing
  for (const s of sets.stems) if (sets.words.has(s)) sets.stems.delete(s);
  const sorted = Object.fromEntries(Object.entries(sets).map(([k, v]) => [k, [...v].sort()]));
  const body = Object.entries(sorted).map(([k, v]) => `export const ${k.toUpperCase()} = ${JSON.stringify(v)};\n`).join('\n');
  const header = `// GENERATED by worker/build-wordlist.mjs from worker/wordlists/*.json. Do not edit by hand.\n// WORDS: whole words. STEMS: long, distinctive strings matched inside a word. PHRASES: abusive phrases. SCAM: spam and scam lines.\n\n`;
  return { text: header + body, counts: Object.fromEntries(Object.entries(sorted).map(([k, v]) => [k, v.length])), dropped };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { text, counts, dropped } = buildWordlist();
  if (process.argv.includes('--check')) {
    const now = existsSync(out) ? readFileSync(out, 'utf8') : '';
    if (now !== text) { console.error('worker/src/wordlist.js is out of date. Run: node worker/build-wordlist.mjs'); process.exit(1); }
    console.log('wordlist.js is up to date', counts);
  } else {
    writeFileSync(out, text);
    console.log('wrote worker/src/wordlist.js', counts);
    for (const d of dropped) console.log('  dropped:', d);
  }
}
